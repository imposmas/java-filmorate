CREATE TABLE IF NOT EXISTS FILMS (
  ID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  NAME VARCHAR(200),
  DESCRIPTION VARCHAR(4000),
  RELEASE_DATE DATE,
  DURATION INTEGER,
  MPA_RATING INTEGER
);

CREATE TABLE IF NOT EXISTS FILM_LIKES (
  FILM_ID INTEGER,
  USER_ID INTEGER,
  PRIMARY KEY (FILM_ID, USER_ID)
);

CREATE TABLE IF NOT EXISTS GENRES (
  ID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  NAME VARCHAR(200) UNIQUE
);

CREATE TABLE IF NOT EXISTS FILM_GENRES (
  FILM_ID INTEGER,
  GENRE_ID INTEGER,
  PRIMARY KEY (FILM_ID, GENRE_ID)
);

CREATE TABLE IF NOT EXISTS MPA_RATINGS (
  ID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  NAME VARCHAR(200) UNIQUE
);

CREATE TABLE IF NOT EXISTS USERS (
  ID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  NAME VARCHAR(200),
  LOGIN VARCHAR(200) UNIQUE,
  EMAIL VARCHAR(200) UNIQUE,
  BIRTHDAY DATE
);

CREATE TABLE IF NOT EXISTS FRIENDS (
  USER_ID INTEGER,
  FRIEND_ID INTEGER,
  STATUS BOOLEAN,
  PRIMARY KEY (USER_ID, FRIEND_ID)
);

ALTER TABLE FILM_LIKES ADD FOREIGN KEY (FILM_ID) REFERENCES FILMS (ID);
ALTER TABLE FILM_LIKES ADD FOREIGN KEY (USER_ID) REFERENCES USERS (ID);

ALTER TABLE FILM_GENRES ADD FOREIGN KEY (FILM_ID) REFERENCES FILMS (ID);
ALTER TABLE FILM_GENRES ADD FOREIGN KEY (GENRE_ID) REFERENCES GENRES (ID);

ALTER TABLE FILMS ADD FOREIGN KEY (MPA_RATING) REFERENCES MPA_RATINGS (ID);

ALTER TABLE FRIENDS ADD FOREIGN KEY (USER_ID) REFERENCES USERS (ID);
ALTER TABLE FRIENDS ADD FOREIGN KEY (FRIEND_ID) REFERENCES USERS (ID);